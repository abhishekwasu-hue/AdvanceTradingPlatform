"""Z10-a (U3 G1): the Pro Chart draws its indicators with its own TypeScript (frontend/src/utils/indicators.ts), written
"to match the backend". This test keeps a small fixture of the backend's values (generated bars in, app.indicators
out) next to that code; frontend/src/utils/indicators.parity.test.ts compares the chart's functions with it. The
fixture must equal what the backend computes today:

    Z10_REGENERATE=1 python -m pytest tests/test_z10a_chart_parity.py      # after an intended indicator change
"""
from __future__ import annotations

import json
import math
import os
from pathlib import Path
from typing import Any, Dict, List, Optional

import pandas as pd

from app.indicators import directional, momentum, trend, volatility, vwap
from app.quality.lookahead import synthetic_bars

FIXTURE = Path(__file__).resolve().parents[2] / "frontend" / "src" / "utils" / "__fixtures__" / "indicator_parity.json"


def _clean(series: Any) -> List[Optional[float]]:
    return [None if v is None or isinstance(v, float) and math.isnan(v) else float(v) for v in pd.Series(series).astype(float).tolist()]


def build() -> Dict[str, Any]:
    bars = synthetic_bars(240, tf="5m", seed=41)
    close = bars["close"]
    st = volatility.supertrend(bars, 10, 3.0)
    ad = directional.adx(bars, 14)
    bb = volatility.bollinger(close, 20, 2.0)
    return {
        "note": "Generated by backend/tests/test_z10a_chart_parity.py from app.indicators - do not edit by hand.",
        "bars": [{"timestamp": ts.isoformat(), "open": float(r.open), "high": float(r.high), "low": float(r.low), "close": float(r.close),
                  "volume": float(r.volume)} for ts, r in zip(bars.index, bars.itertuples())],
        "series": {
            "ema_9": _clean(trend.ema(close, 9)),
            "ema_21": _clean(trend.ema(close, 21)),
            "sma_20": _clean(trend.sma(close, 20)),
            "rsi_14": _clean(momentum.rsi(close, 14)),
            "atr_14": _clean(volatility.atr(bars, 14)),
            "adx_14": _clean(ad["adx"]),
            "plus_di_14": _clean(ad["plus_di"]),
            "minus_di_14": _clean(ad["minus_di"]),
            "supertrend_10_3": _clean(st["supertrend"]),
            "supertrend_10_3_direction": [None if math.isnan(v) else int(d) for v, d in zip(st["supertrend"], st["trend"])],
            "bb_mid_20_2": _clean(bb["mid"]),
            "bb_upper_20_2": _clean(bb["upper"]),
            "bb_lower_20_2": _clean(bb["lower"]),
            "vwap": _clean(vwap.session_vwap(bars)),
        },
    }


def _dump(data: Dict[str, Any]) -> str:
    """One line per bar / series: small diffs when an indicator changes."""
    lines = ["{", f'  "note": {json.dumps(data["note"])},', '  "bars": [']
    lines += [f"    {json.dumps(b)}," for b in data["bars"]]
    lines[-1] = lines[-1].rstrip(",")
    lines += ["  ],", '  "series": {']
    lines += [f"    {json.dumps(k)}: {json.dumps(v)}," for k, v in data["series"].items()]
    lines[-1] = lines[-1].rstrip(",")
    lines += ["  }", "}", ""]
    return "\n".join(lines)


def test_chart_parity_fixture_matches_the_backend():
    want = _dump(build())
    if os.environ.get("Z10_REGENERATE"):
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(want)
    assert FIXTURE.exists(), f"missing {FIXTURE} - run with Z10_REGENERATE=1"
    assert json.loads(FIXTURE.read_text()) == json.loads(want), "the chart parity fixture is stale - run with Z10_REGENERATE=1"
    data = json.loads(want)
    assert {1, -1} <= {d for d in data["series"]["supertrend_10_3_direction"] if d is not None}      # it flips: not vacuous
    assert len({b["timestamp"][:10] for b in data["bars"]}) >= 3                                    # several sessions (VWAP resets)
