import { Layers, Newspaper } from "lucide-react";
import { Fragment, useState } from "react";
import { api } from "../../../api/client";
import { ApiError } from "../../../api/errors";
import { Badge, Button, fieldClass } from "../../../components/primitives";
import type { MultiView, MultiViewAnalysis } from "../../../types";
import { useAiTask } from "../../aiTask";
import AiProgress from "../../components/AiProgress";
import CostChip from "../../components/CostChip";
import { useCopilotT } from "../../i18n";
import { Panel } from "../shared";
import { cleanSymbol, factRows, headlines, sections, totalUsage } from "./multiview";

/**
 * H-C4: "analyze <symbol>" - the technical, options, news and macro views from the platform's read tools, then the
 * readings that lean up and down, the risks and what would change the picture. A description of the situation, never
 * advice. Rules-only wording (round cap, docs/OPEN_QUESTIONS.md HC4-5): every sentence shown is generated by the
 * platform's rules from the data - no AI-written text - and nothing is acted on. Behind `ai_multiview`.
 */
const EXCHANGES = ["NSE", "BSE", "NFO", "MCX"] as const;

function ViewCard({ view }: { view: MultiView }) {
  const t = useCopilotT();
  const rows = factRows(view);
  const news = headlines(view);
  return (
    <div className="rounded-xl border border-border bg-surface-2/50 p-3" data-testid={`multiview-${view.id}`}>
      <div className="mb-1.5 flex flex-wrap items-center gap-1.5 text-sm">
        <b className="text-fg">{view.label}</b>
        <Badge className="ml-auto" tone={view.ok ? "neutral" : "warn"}>
          {view.ok ? t("analyze.byRules") : t("analyze.notRead")}
        </Badge>
      </div>
      {view.ok ? <p className="text-sm text-fg">{view.report}</p> : <p className="text-xs text-fg-muted">{view.error ?? t("analyze.notRead")}</p>}
      {view.untrusted && news.length > 0 && (
        <div className="mt-2">
          <p className="flex items-center gap-1 text-[11px] text-fg-muted"><Newspaper size={11} aria-hidden />{t("analyze.untrusted")}</p>
          <ul className="mt-1 space-y-0.5 text-xs text-fg-muted">
            {news.map((h, i) => (
              <li key={i}>· {h.headline}{h.source ? ` (${h.source}${h.verified ? `, ${t("analyze.verified")}` : ""})` : ""}</li>
            ))}
          </ul>
        </div>
      )}
      {rows.length > 0 && (
        <details className="mt-2 text-xs">
          <summary className="cursor-pointer text-fg-muted">{t("analyze.facts")}</summary>
          <dl className="mt-1 grid grid-cols-2 gap-x-3 gap-y-0.5">
            {rows.map(([k, v]) => (<Fragment key={k}><dt className="text-fg-muted">{k}</dt><dd className="text-fg tabular-nums">{v}</dd></Fragment>))}
          </dl>
        </details>
      )}
      <p className="mt-2 text-[11px] text-fg-muted">
        {view.as_of ? t("analyze.asOf", { when: new Date(view.as_of).toLocaleString("en-IN") }) : t("analyze.noTime")}
        {view.sources.length > 0 ? ` · ${view.sources.join(", ")}` : ""}
      </p>
    </div>
  );
}

export default function MultiViewPanel({ initialSymbol = "NIFTY 50" }: { initialSymbol?: string }) {
  const t = useCopilotT();
  const task = useAiTask(t);                                    // 90 s: the server caps an analysis at 60 s
  const [symbol, setSymbol] = useState(initialSymbol);
  const [exchange, setExchange] = useState<(typeof EXCHANGES)[number]>("NSE");
  const [result, setResult] = useState<MultiViewAnalysis | null>(null);
  const [off, setOff] = useState(false);
  const clean = cleanSymbol(symbol);

  async function analyze() {
    if (!clean || task.busy) return;
    const out = await task.run([t("analyze.step.gather"), t("analyze.step.summary")], async (signal) => {
      try {
        return await api.aiAnalyze(clean, exchange, "en", signal);      // the UI is English, so is the analysis
      } catch (e) {
        if (e instanceof ApiError && e.status === 503 && /ai_multiview|ai_copilot/.test(e.body ?? "")) { setOff(true); return null; }
        throw e;
      }
    });
    if (out) { setResult(out); setOff(false); }
  }

  const usage = result ? totalUsage(result) : null;
  return (
    <Panel title={t("analyze.title")} icon={<Layers size={15} />} testId="multiview">
      <p className="mb-2 text-xs text-fg-muted">{t("analyze.intro")}</p>
      <form className="flex flex-wrap items-end gap-2" onSubmit={(e) => { e.preventDefault(); void analyze(); }}>
        <label className="flex flex-col text-xs text-fg-muted">{t("analyze.symbol")}
          <input className={`${fieldClass} w-44`} value={symbol} maxLength={40} onChange={(e) => setSymbol(e.target.value)} />
        </label>
        <label className="flex flex-col text-xs text-fg-muted">{t("analyze.exchange")}
          <select className={`${fieldClass} w-24`} value={exchange} onChange={(e) => setExchange(e.target.value as (typeof EXCHANGES)[number])}>
            {EXCHANGES.map((x) => <option key={x} value={x}>{x}</option>)}
          </select>
        </label>
        <Button type="submit" variant="primary" icon={<Layers size={13} />} disabled={!clean || task.busy}>{t("analyze.run")}</Button>
      </form>
      {off && <p className="mt-2 text-sm text-fg-muted">{t("analyze.off")}</p>}
      <AiProgress state={task.state} onCancel={task.cancel} onRetry={() => void analyze()} />
      {result && (
        <div className="mt-3 space-y-3">
          <div className="rounded-xl border border-border p-3" data-testid="multiview-summary">
            <div className="mb-1 flex flex-wrap items-center gap-1.5">
              <b className="text-sm text-fg">{t("analyze.summary", { symbol: result.symbol })}</b>
              <Badge tone="neutral">{t("analyze.byRules")}</Badge>
              {usage && <CostChip tokens={usage.tokens} inr={usage.inr} />}
            </div>
            <p className="text-sm text-fg">{result.summary.situation}</p>
            <div className="mt-2 grid gap-2 md:grid-cols-2">
              {sections(result.summary).map((s) => (
                <div key={s.key}>
                  <p className="text-xs font-semibold text-fg-muted">{t(`analyze.section.${s.key}`)}</p>
                  <ul className="mt-0.5 space-y-0.5 text-xs text-fg">{s.items.map((x, i) => <li key={i}>· {x}</li>)}</ul>
                </div>
              ))}
            </div>
          </div>
          <div className="grid gap-2 md:grid-cols-2">{result.views.map((v) => <ViewCard key={v.id} view={v} />)}</div>
          {result.limits_note && <p className="text-[11px] text-fg-muted">{result.limits_note}</p>}
          <p className="text-[11px] text-fg-muted">{result.note}</p>
        </div>
      )}
    </Panel>
  );
}
