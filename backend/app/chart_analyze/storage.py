"""Analyze a chart: the private file store for the users' chart images.

Where: the directory named by `CHART_ANALYZE_DATA_DIR` (deployment configuration, like the other paths in `.env`),
default `/data/private/chart_analyze` - the backend's private data volume (`private_data` in docker-compose.yml,
mounted only into the backend and the worker; never served by the web server, never in an image, never in git). A
directory inside the source tree is refused, so a misconfiguration cannot put users' images next to the code.

Layout: `<root>/<tenant id>/<32 hex characters>.png`. Every part is generated by the server (the tenant id is an
integer from the database, the name is `uuid4().hex`); nothing the user sends becomes part of a path, and every path is
checked to resolve inside the root before it is opened. Directories are created 0700 and files 0600; a file is written
to a temporary name and renamed, so a reader never sees half a file.
"""
import os
import re
import uuid
from pathlib import Path
from typing import Optional

ENV = "CHART_ANALYZE_DATA_DIR"
DEFAULT_ROOT = "/data/private/chart_analyze"
_NAME = re.compile(r"^[1-9][0-9]{0,9}/[0-9a-f]{32}\.png$")


def _source_tree() -> Path:
    """The code's own tree: the directory holding the `app` package (`/app` in the image, `backend/` in a checkout),
    widened to the repository when it is a git checkout."""
    code = Path(__file__).resolve().parents[2]
    return code.parent if (code.parent / ".git").exists() else code


_SOURCE_TREE = _source_tree()


class StorageUnavailable(RuntimeError):
    """The private store is not configured or not writable (the API answers 503 and stores nothing)."""


def root() -> Path:
    raw = (os.environ.get(ENV) or DEFAULT_ROOT).strip()
    path = Path(raw).expanduser()
    if not path.is_absolute():
        raise StorageUnavailable(f"{ENV} must be an absolute path")
    resolved = path.resolve()
    if resolved == _SOURCE_TREE or _SOURCE_TREE in resolved.parents:
        raise StorageUnavailable(f"{ENV} points inside the source tree; use the private data volume")
    return resolved


def _checked(relative: str) -> Path:
    if not isinstance(relative, str) or not _NAME.fullmatch(relative):
        raise ValueError("not a chart image path")
    base = root()
    full = (base / relative).resolve()
    if base not in full.parents:
        raise ValueError("path outside the private store")
    return full


def new_name(tenant_id: int) -> str:
    tid = int(tenant_id)
    if tid <= 0:
        raise ValueError("tenant id")
    return f"{tid}/{uuid.uuid4().hex}.png"


def write(relative: str, data: bytes) -> None:
    full = _checked(relative)
    try:
        base = root()
        base.mkdir(mode=0o700, parents=True, exist_ok=True)
        full.parent.mkdir(mode=0o700, exist_ok=True)
        tmp = full.with_name(full.name + ".part")
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
        os.replace(tmp, full)
    except OSError as exc:
        raise StorageUnavailable(f"the private store is not writable ({exc.__class__.__name__})") from None


def read(relative: str) -> Optional[bytes]:
    try:
        return _checked(relative).read_bytes()
    except (OSError, ValueError, StorageUnavailable):
        return None


def delete(relative: Optional[str]) -> bool:
    """Removes the file; True when it is gone (also when it was already gone)."""
    if not relative:
        return True
    try:
        _checked(relative).unlink(missing_ok=True)
        return True
    except (OSError, ValueError, StorageUnavailable):
        return False
