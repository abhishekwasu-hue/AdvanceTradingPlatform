"""Z10-c (G6): every `/api/*` route and who may call it. tests/test_z10c_tenancy_sweep.py fails when a route exists
that this table does not classify (or the table lists a route that no longer exists), so every new route - including
the ones open PRs add - is classified when it merges, and the sweep then tests it like the others.

Classes (the sweep checks each against the route's dependencies and with real requests):
- "public: <why>"  no login (catalogues, health probes, sign-in flows, webhooks with a secret token);
- "key"            the public REST API: an API key, never a login token;
- "admin"          SUPER_ADMIN only (a tenant OWNER gets 403);
- "owner"          the organisation's OWNER (team:manage); a plain member and a VIEWER get 403;
- "trader"         a write that needs a trading role and scope; a VIEWER and a member denied every scope get 403;
- "member"         a read by any logged-in member of the organisation; "member: <why>" names a read that returns only the
                   caller's own rows (never another member's, BT1b);
- "self: <why>"    a write any member may make, because it touches only the caller's own data or computes and stores
                   nothing (a VIEWER may do it).
Every route except "public" refuses an anonymous request, and none lets another organisation read or change this
organisation's rows. To classify a new route: pick the class its dependencies give it (the sweep prints the
suggestion) and, for "public" / "self", say why.
"""
